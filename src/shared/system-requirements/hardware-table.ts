/**
 * Hand-curated relative performance scores, used to compare a PC with a
 * game's requirements. Approximate by design: each is "how fast in games",
 * scaled so a GTX 1060 is 100 (GPUs) and a Core i5-8400 is 100 (CPUs). The two
 * scales are never compared with each other. Models newer than this table are
 * "unknown" to the checker, not wrong; add them here.
 */
export interface HardwareModel {
  id: string;
  name: string;
  score: number;
}

const toModels = (entries: [string, number][]): HardwareModel[] =>
  entries.map(([name, score]) => ({
    id: name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-|-$/g, ""),
    name,
    score,
  }));

